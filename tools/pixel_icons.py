def _battery(w, h, tw, bars, bolt=None):
    """a battery w x h, its terminal tw wide past it, bars of the four lit; bolt: the charging bolt's rows (x0, x1)"""
    bw = (w - 4 - 3) // 4
    rows = [["#" if y in (0, h - 1) or x in (0, w - 1) else "." for x in range(w)] + ["."] * tw for y in range(h)]
    for y in range(h // 2 - 2 + h % 2, h // 2 + 2):
        rows[y][w:] = ["#"] * tw
    for b in range(bars):
        for y in range(2, h - 2):
            for x in range(2 + (bw + 1) * b, 2 + (bw + 1) * b + bw):
                rows[y][x] = "#"
    for y, (x0, x1) in enumerate(bolt or [], 1):
        for x in range(x0, x1 + 1):
            rows[y][x] = "#"
    return "\n".join("".join(r) for r in rows)


