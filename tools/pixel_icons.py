def hand_cell(art, s):
    """an ASCII drawing centred in an s x s cell -> s * s nibbles (0 or INK)"""
    rows = art.strip("\n").split("\n")
    h, w = len(rows), max(len(r) for r in rows)
    assert h <= s and w <= s, f"a {w} x {h} drawing in a {s} px cell"
    x0, y0 = (s - w) // 2, (s - h) // 2
    cell = [0] * (s * s)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == "#":
                cell[(y0 + y) * s + x0 + x] = INK
    return cell


SS = 16


def auto_cell(font, s, codepoint):
    """the glyph in 1 bit: of the sub-pixel shifts (an eighth of a pixel apart, half a pixel at most) the one leaving the
    fewest half-covered pixels, thresholded at half coverage"""
    hi = ar.render_cell(ar.open_font(font, s * SS), chr(codepoint), (s * SS + SS, s * SS + SS), SS // 2, SS // 2,
                        anchor="la")
    best = None
    for dy in range(-SS // 2, SS // 2 + 1, 2):
        for dx in range(-SS // 2, SS // 2 + 1, 2):
            x0, y0 = SS // 2 - dx, SS // 2 - dy
            cov = list(hi.crop((x0, y0, x0 + s * SS, y0 + s * SS)).reduce(SS).tobytes())
            blur = sum(min(a, 255 - a) for a in cov) + 8 * (abs(dx) + abs(dy))
            if best is None or blur < best[0]:
                best = (blur, cov)
    return [INK if a >= 128 else 0 for a in best[1]]


def pixel_cell(name, s, font, codepoint):
    art = HAND.get((name, s))
    return hand_cell(art, s) if art else auto_cell(font, s, codepoint)
